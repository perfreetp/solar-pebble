/**
 * OBJ 网格导出：257×257 规则网格，三角形面。
 * 坐标轴约定：x 向东，y 向上（高度），z 向北；与渲染器一致。
 */
export function buildObj(heights, verts, step) {
  const half = (verts - 1) * step / 2
  const lines = []
  lines.push('o terrain')
  lines.push('# robot test field terrain, generated by terrain-editor')
  lines.push(`# grid ${verts}x${verts}, cell ${step.toFixed(5)}m`)

  // 顶点（OBJ 索引从 1 开始）
  for (let k = 0; k < verts; k++) {
    const z = -half + k * step
    for (let i = 0; i < verts; i++) {
      const x = -half + i * step
      const y = heights[k * verts + i]
      lines.push(`v ${x.toFixed(4)} ${y.toFixed(4)} ${z.toFixed(4)}`)
    }
  }
  lines.push('vn 0 1 0')

  const vid = (i, k) => k * verts + i + 1
  for (let k = 0; k < verts - 1; k++) {
    for (let i = 0; i < verts - 1; i++) {
      const a = vid(i, k)
      const b = vid(i + 1, k)
      const c = vid(i, k + 1)
      const d = vid(i + 1, k + 1)
      lines.push(`f ${a} ${b} ${c}`)
      lines.push(`f ${b} ${d} ${c}`)
    }
  }
  return new Blob([lines.join('\n') + '\n'], { type: 'text/plain' })
}
